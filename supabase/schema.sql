create or replace function serve_order_item(p_order_item_id bigint, p_actor_user_id uuid)
returns void
language plpgsql
as $$
declare
  v_item order_items%rowtype;
  v_recipe record;
begin
  select * into v_item from order_items where order_item_id = p_order_item_id;
  if not found or v_item.status not in ('ready', 'out_for_serving') then
    raise exception 'Only ready or out-for-serving items can be served';
  end if;

  if exists (
    select 1
    from recipes r
    join inventory_items i on i.ingredient_id = r.ingredient_id
    where r.menu_id = v_item.menu_id
      and i.deleted_at is null
      and i.quantity_on_hand < r.quantity_used * v_item.quantity
  ) then
    raise exception 'Ingredient stock is too low to serve this item';
  end if;

  for v_recipe in
    select r.ingredient_id, r.quantity_used, i.unit_cost
    from recipes r
    join inventory_items i on i.ingredient_id = r.ingredient_id
    where r.menu_id = v_item.menu_id
  loop
    update inventory_items
    set quantity_on_hand = quantity_on_hand - (v_recipe.quantity_used * v_item.quantity)
    where ingredient_id = v_recipe.ingredient_id;

    insert into inventory_transactions (
      ingredient_id,
      order_item_id,
      transaction_type,
      quantity_change,
      unit_cost_snapshot,
      occurred_at
    )
    values (
      v_recipe.ingredient_id,
      p_order_item_id,
      'usage',
      -(v_recipe.quantity_used * v_item.quantity),
      v_recipe.unit_cost,
      now()
    );
  end loop;

  update order_items
  set status = 'served',
      out_for_serving_at = coalesce(out_for_serving_at, now()),
      served_at = coalesce(served_at, now())
  where order_item_id = p_order_item_id;

  update orders
  set status = 'completed'
  where order_id = v_item.order_id
    and not exists (
      select 1 from order_items
      where order_id = v_item.order_id
        and status not in ('served', 'cancelled')
    );

  insert into staff_activity_logs (user_id, action, entity_type, entity_id)
  values (p_actor_user_id, 'serve_item', 'order_item', p_order_item_id::text);
end;
$$;

