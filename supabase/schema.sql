create or replace function request_bill(p_session_id uuid, p_cashier_user_id uuid)
returns void
language plpgsql
as $$
declare
  v_table_code varchar(2);
begin
  select table_code into v_table_code from dining_sessions where session_id = p_session_id and status = 'open';
  if v_table_code is null then
    raise exception 'Open dining session not found';
  end if;

  update dining_sessions set bill_requested_at = now() where session_id = p_session_id;
  update restaurant_tables set status = 'billing', cleaning_started_at = null where table_code = v_table_code;

  insert into staff_activity_logs (user_id, action, entity_type, entity_id)
  values (p_cashier_user_id, 'request_bill', 'dining_session', p_session_id::text);
end;
$$;

create or replace function process_cash_payment(p_session_id uuid, p_cashier_user_id uuid)
returns numeric
language plpgsql
as $$
declare
  v_session dining_sessions%rowtype;
  v_total numeric(10,2);
begin
  select * into v_session from dining_sessions where session_id = p_session_id and status = 'open';
  if not found then
    raise exception 'Open dining session not found';
  end if;

  v_total :=
    v_session.adult_count * v_session.adult_price_snapshot +
    v_session.child_count * v_session.child_price_snapshot;

  update order_items
  set status = 'cancelled', cancelled_at = coalesce(cancelled_at, now())
  where order_id in (select order_id from orders where session_id = p_session_id)
    and status in ('pending', 'cooking', 'ready', 'out_for_serving');

  insert into payments (session_id, cashier_id, method, paid_amount, paid_at, status)
  values (p_session_id, p_cashier_user_id, 'cash', v_total, now(), 'paid');

  update dining_sessions
  set status = 'closed', payment_status = 'paid', closed_at = now()
  where session_id = p_session_id;

  update restaurant_tables
  set status = 'cleaning', cleaning_started_at = now()
  where table_code = v_session.table_code;

  insert into staff_activity_logs (user_id, action, entity_type, entity_id)
  values (p_cashier_user_id, 'checkout_paid', 'dining_session', p_session_id::text);

  return v_total;
end;
$$;

