-- This function makes the served action safe: check stock, deduct inventory, then mark served.
create or replace function serve_order_item(p_order_item_id bigint, p_staff_id uuid)
returns void
language plpgsql
as $$
declare
  v_item order_items%rowtype;
  v_recipe record;
  v_required numeric(12,2);
  v_shift_id bigint;
begin
  select *
  into v_item
  from order_items
  where order_item_id = p_order_item_id
  for update;

  if not found then
    raise exception 'Order item % does not exist', p_order_item_id;
  end if;

  if v_item.status <> 'out_for_serving' then
    raise exception 'Order item % must be out for serving before it can be served', p_order_item_id;
  end if;

  for v_recipe in
    select r.ingredient_id, r.quantity_used, i.quantity_on_hand, i.name, i.unit_cost
    from recipes r
    join inventory_items i on i.ingredient_id = r.ingredient_id
    where r.menu_id = v_item.menu_id
    for update of i
  loop
    v_required := v_recipe.quantity_used * v_item.quantity;

    if v_recipe.quantity_on_hand < v_required then
      raise exception 'Not enough stock for %. Required %, available %', v_recipe.name, v_required, v_recipe.quantity_on_hand;
    end if;
  end loop;

  for v_recipe in
    select r.ingredient_id, r.quantity_used, i.unit_cost
    from recipes r
    join inventory_items i on i.ingredient_id = r.ingredient_id
    where r.menu_id = v_item.menu_id
    for update of i
  loop
    v_required := v_recipe.quantity_used * v_item.quantity;

    update inventory_items
    set quantity_on_hand = quantity_on_hand - v_required
    where ingredient_id = v_recipe.ingredient_id;

    insert into inventory_transactions (
      ingredient_id,
      order_item_id,
      staff_id,
      transaction_type,
      quantity_change,
      unit_cost_snapshot,
      occurred_at,
      note
    )
    values (
      v_recipe.ingredient_id,
      p_order_item_id,
      p_staff_id,
      'usage',
      -v_required,
      v_recipe.unit_cost,
      now(),
      'Served order item'
    );

    perform sync_menu_availability_for_stock(v_recipe.ingredient_id);
  end loop;

  update order_items
  set status = 'served',
      served_at = now()
  where order_item_id = p_order_item_id;

  select shift_id
  into v_shift_id
  from staff_shifts
  where user_id = p_staff_id
    and clock_out_at is null
  order by clock_in_at desc
  limit 1;

  insert into staff_activity_logs (
    user_id,
    shift_id,
    action,
    entity_type,
    entity_id,
    occurred_at,
    note
  )
  values (
    p_staff_id,
    v_shift_id,
    'serve_item',
    'order_item',
    p_order_item_id::text,
    now(),
    'Waiter marked item served and inventory was deducted'
  );

  update orders
  set status = 'completed'
  where order_id = v_item.order_id
    and not exists (
      select 1
      from order_items oi
      where oi.order_id = v_item.order_id
        and oi.status in ('pending', 'cooking', 'ready', 'out_for_serving')
    );
end;
$$;

comment on function serve_order_item(bigint, uuid) is 'Atomic waiter action: verify recipe stock, deduct inventory, write transactions, and mark the order item served.';

