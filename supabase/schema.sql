-- Staff users hold every login role required by the UX feedback.
create table if not exists app_users (
  user_id uuid primary key default gen_random_uuid(),
  full_name varchar(120) not null,
  username varchar(60) not null unique,
  password_hash text not null,
  role staff_role not null,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  deleted_at timestamptz
);

comment on table app_users is 'Staff login table for cashier, kitchen, waiter, and manager roles. Customers do not log in.';
comment on column app_users.deleted_at is 'Soft delete timestamp; inactive staff stay available for historical cashier/order references.';

-- Staff shifts are created immediately after successful staff authentication.
create table if not exists staff_shifts (
  shift_id bigint generated by default as identity primary key,
  user_id uuid not null references app_users(user_id),
  role_snapshot staff_role not null,
  station varchar(80) not null,
  clock_in_at timestamptz not null default now(),
  clock_out_at timestamptz,
  login_at timestamptz not null default now(),
  logout_at timestamptz,
  note text not null default '',
  check (clock_out_at is null or clock_out_at >= clock_in_at),
  check (logout_at is null or logout_at >= login_at)
);

comment on table staff_shifts is 'Clock-in/clock-out history created by the staff portal for work-hour reporting and staff accountability.';
comment on column staff_shifts.role_snapshot is 'Copies the role at login time so historical shifts stay correct even if a staff role changes later.';
comment on column staff_shifts.station is 'Work station chosen from the login role, such as Front POS, Kitchen pass, Dining room, or Management office.';

-- Staff activity logs connect operational actions to the authenticated user and active shift.
create table if not exists staff_activity_logs (
  activity_id bigint generated by default as identity primary key,
  user_id uuid not null references app_users(user_id),
  shift_id bigint references staff_shifts(shift_id),
  action varchar(80) not null,
  entity_type varchar(40) not null,
  entity_id text not null,
  occurred_at timestamptz not null default now(),
  note text not null default ''
);

comment on table staff_activity_logs is 'Audit trail for login, order, kitchen, payment, inventory, and manager actions.';
comment on column staff_activity_logs.entity_type is 'Table or business object affected, for example dining_session, order_item, payment, menu_item, or inventory_item.';

-- Restaurant tables are assigned to exactly one open dining session at a time.
create table if not exists restaurant_tables (
  table_id bigint generated by default as identity primary key,
  table_code varchar(12) not null unique,
  zone varchar(40) not null,
  capacity integer not null default 4 check (capacity = 4),
  status table_status not null default 'available',
  cleaning_started_at timestamptz,
  created_at timestamptz not null default now(),
  deleted_at timestamptz
);

comment on table restaurant_tables is 'Physical dine-in tables that cashiers open and release.';
comment on column restaurant_tables.status is 'available means ready for check-in; occupied means guests are seated; billing means cash payment is pending; cleaning means the 10-minute reset timer is running.';
comment on column restaurant_tables.cleaning_started_at is 'Set when cash checkout moves a table to cleaning; when 10 minutes pass the app or a scheduled job should mark it available.';

-- Dining sessions are the main transaction boundary for buffet guests.
create table if not exists dining_sessions (
  session_id uuid primary key default gen_random_uuid(),
  table_id bigint not null references restaurant_tables(table_id),
  cashier_id uuid not null references app_users(user_id),
  waiter_id uuid references app_users(user_id),
  adult_count integer not null default 0 check (adult_count >= 0),
  child_count integer not null default 0 check (child_count >= 0),
  adult_price numeric(10,2) not null default 0 check (adult_price >= 0),
  child_price numeric(10,2) not null default 0 check (child_price >= 0),
  opened_at timestamptz not null default now(),
  bill_requested_at timestamptz,
  closed_at timestamptz,
  status session_status not null default 'open',
  payment_status payment_status not null default 'unpaid',
  customer_code varchar(20) not null unique,
  check (adult_count + child_count > 0),
  check (adult_count + child_count <= 4)
);

comment on table dining_sessions is 'One buffet visit for one table; stores guest counts and prices needed for revenue and cost-per-head reports.';
comment on column dining_sessions.opened_at is 'Used for peak-hour and average dining-time dashboard queries.';
comment on column dining_sessions.bill_requested_at is 'Set when guests request a cash bill; drives the cashier payment state.';
comment on column dining_sessions.closed_at is 'Filled when cashier closes and pays the session.';

-- Payments store cashier checkout data separately from sessions.
