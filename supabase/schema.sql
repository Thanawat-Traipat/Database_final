-- Cashier payment helpers match the new billing flow.
create or replace function request_cash_bill(p_session_id uuid, p_cashier_id uuid)
returns void
language plpgsql
as $$
declare
  v_session dining_sessions%rowtype;
begin
  select *
  into v_session
  from dining_sessions
  where session_id = p_session_id
    and status = 'open'
  for update;

  if not found then
    raise exception 'Open dining session % does not exist', p_session_id;
  end if;

  update dining_sessions
  set bill_requested_at = coalesce(bill_requested_at, now())
  where session_id = p_session_id;

  update restaurant_tables
  set status = 'billing'
  where table_id = v_session.table_id;

  insert into staff_activity_logs (user_id, shift_id, action, entity_type, entity_id, occurred_at, note)
  values (p_cashier_id, active_shift_id(p_cashier_id), 'request_bill', 'dining_session', p_session_id::text, now(), 'Cash bill requested');
end;
$$;

comment on function request_cash_bill(uuid, uuid) is 'Cashier action: moves an open table into the red billing payment state.';

create or replace function cash_checkout_session(
  p_session_id uuid,
  p_cashier_id uuid,
  p_paid_amount numeric default null
)
returns void
language plpgsql
as $$
declare
  v_session dining_sessions%rowtype;
  v_paid_amount numeric(10,2);
  v_cancelled_count integer;
begin
  select *
  into v_session
  from dining_sessions
  where session_id = p_session_id
    and status = 'open'
  for update;

  if not found then
    raise exception 'Open dining session % does not exist', p_session_id;
  end if;

  v_paid_amount := coalesce(
    p_paid_amount,
    v_session.adult_count * v_session.adult_price + v_session.child_count * v_session.child_price
  );

  update order_items oi
  set status = 'cancelled',
      cancelled_at = coalesce(cancelled_at, now())
  from orders o
  where o.order_id = oi.order_id
    and o.session_id = p_session_id
    and oi.status in ('pending', 'cooking', 'ready', 'out_for_serving');

  get diagnostics v_cancelled_count = row_count;

  insert into payments (session_id, cashier_id, method, paid_amount, paid_at, status)
  values (p_session_id, p_cashier_id, 'cash', v_paid_amount, now(), 'paid')
  on conflict (session_id) do update
    set cashier_id = excluded.cashier_id,
        method = excluded.method,
        paid_amount = excluded.paid_amount,
        paid_at = excluded.paid_at,
        status = excluded.status;

  update dining_sessions
  set status = 'closed',
      payment_status = 'paid',
      closed_at = coalesce(closed_at, now())
  where session_id = p_session_id;

  update restaurant_tables
  set status = 'cleaning',
      cleaning_started_at = now()
  where table_id = v_session.table_id;

  update orders
  set status = 'completed'
  where session_id = p_session_id
    and not exists (
      select 1
      from order_items oi
      where oi.order_id = orders.order_id
        and oi.status in ('pending', 'cooking', 'ready', 'out_for_serving')
    );

  insert into staff_activity_logs (user_id, shift_id, action, entity_type, entity_id, occurred_at, note)
  values (
    p_cashier_id,
    active_shift_id(p_cashier_id),
    'checkout_paid',
    'dining_session',
    p_session_id::text,
    now(),
    'Cash checkout completed; cancelled unfinished kitchen items: ' || v_cancelled_count::text
  );
end;
$$;

comment on function cash_checkout_session(uuid, uuid, numeric) is 'Cashier action: cash-only payment, cancels unfinished items, closes the session, and starts the 10-minute cleaning timer.';

-- This function moves ready kitchen food into the waiter delivery state.
create or replace function send_order_item_to_table(p_order_item_id bigint, p_staff_id uuid)
